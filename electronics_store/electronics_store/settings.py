def build_celery_broker_url():
    if url := os.environ.get('CELERY_BROKER_URL'):
        return url

    user = quote(os.environ.get('RABBITMQ_DEFAULT_USER', 'guest'), safe='')
    password = quote(
        read_secret('rabbitmq_password') or os.environ.get('RABBITMQ_DEFAULT_PASS', 'guest'),
        safe='',
    )
    host = os.environ.get('RABBITMQ_HOST', '127.0.0.1' if DEBUG else 'rabbitmq')
    port = os.environ.get('RABBITMQ_PORT', '5672')
    vhost = quote(os.environ.get('RABBITMQ_VHOST', '/'), safe='')
    return f'amqp://{user}:{password}@{host}:{port}/{vhost}'


